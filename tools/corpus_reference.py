"""Writes tests/corpus_reference.hpp from the song corpus's features_ref.json: for each group of
excerpts a preset answers to, the 25th percentile, median and 75th percentile (numpy's linear
percentiles, as song-corpus/scripts/compare.py takes them) of the features tests/corpus_gate.hpp
measures, for one separated stem. Only numbers leave the corpus; no audio is copied.

It also measures, with the corpus's own extractor (song-corpus/scripts/features.py, so librosa is
needed), the University of Iowa tuba playing the tuba line, mezzo-forte and fortissimo, dry and
through the home tape, as `build/honkr-corpus-render iowa-tuba` writes them: each take, and the
taped takes' range (lowest, mean, highest) as the group Iowa_tuba_taped.

    build/honkr-corpus-render iowa-tuba ~/.cache/honkr-references /tmp/iowa-tuba
    .../.claude-gpu-audio/bin/python -I tools/corpus_reference.py /path/to/song-corpus/features_ref.json /tmp/iowa-tuba > tests/corpus_reference.hpp

OTC_winds is the OTC excerpts whose `other` stem plausibly carries the horns, judged without
listening from each excerpt's `other` stem: present (share of the mix above -30 dB), tonal (median
spectral flatness under -75 dB, harmonic over percussive energy by more than 4 dB after HPSS),
pitched in a horn section's register (pyin median f0 between 90 and 1000 Hz) and not sitting in
the bass register (85% roll-off above 400 Hz). The seven left out, and the test that failed:
Another Set of Bees in the Museum (flatness -73 dB), Combinations (f0 81 Hz, roll-off 248 Hz),
I Can Smell The Leaves (roll-off 156 Hz), I Won this Dog at the Driftwood (flatness -72 dB,
harmonic over percussive 2 dB), Marking Time (f0 58 Hz), The Game You Play Is In Your Head
(flatness -71 dB), The Giant Day / Dusk (share -43 dB, 4% voiced).
"""
import importlib.util
import json
import os
import statistics
import sys

OTC_WINDS = ['OTC_Define_A_Transparent_Dream', 'OTC_Hideway', 'OTC_I_Have_Been_Floated', 'OTC_The_Opera_House',
             'OTC_The_Sylvan_Screen']
GROUPS = [
    ('OTC_winds', 'other', lambda i: i in OTC_WINDS),
    ('OTC', 'other', lambda i: i.startswith('OTC_')),
    ('OTC', 'bass', lambda i: i.startswith('OTC_')),
]
FEATURES = ['centroid_hz', 'rolloff85_hz', 'corr', 'wobble_cents']
TAKES = [('mf', 'dry'), ('mf', 'taped'), ('ff', 'dry'), ('ff', 'taped')]


def iowa_tuba(features_ref, renders):
    spec = importlib.util.spec_from_file_location('features', os.path.join(os.path.dirname(os.path.abspath(features_ref)), 'scripts', 'features.py'))
    features = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(features)
    return {take: features.measure({'bass': os.path.join(renders, 'iowa-tuba-%s-%s_bass.wav' % take)})['bass'] for take in TAKES}


def percentile(values, q):
    v = sorted(values)
    pos = (len(v) - 1) * q / 100.0
    lo = int(pos)
    hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (pos - lo)


def main():
    data = json.load(open(sys.argv[1]))
    takes = iowa_tuba(sys.argv[1], sys.argv[2])
    out = ['// Generated by tools/corpus_reference.py from song-corpus/features_ref.json, measured from',
           '// the user\'s own records (htdemucs_6s stems of 45 s excerpts), and from the University of Iowa',
           '// tuba playing the tuba line (tools/corpus_render.cpp iowa-tuba). Numbers only.',
           '#pragma once', '', '#include <array>', '', 'namespace honkr::corpus {', '',
           'struct Stat { double q25, median, q75; };',
           'struct Reference {',
           '  const char* group;',
           '  const char* stem;',
           '  int excerpts;',
           '  Stat centroid_hz, rolloff85_hz, corr, wobble_cents;',
           '};',
           'struct Take {',
           '  const char* dynamic;',
           '  bool taped;',
           '  double centroid_hz, rolloff85_hz, corr, wobble_cents;',
           '};', '',
           'inline constexpr std::array kIowaTuba{']
    for (dynamic, transfer), r in takes.items():
        out.append('    Take{"%s", %s, %s},' % (dynamic, 'true' if transfer == 'taped' else 'false', ', '.join('%.4g' % r[name] for name in FEATURES)))
    out += ['};', '', 'inline constexpr std::array kReferences{']
    for group, stem, member in GROUPS:
        rows = [data[i][stem] for i in sorted(data) if member(i) and stem in data[i]]
        stats = []
        for name in FEATURES:
            values = [r[name] for r in rows if r.get(name) is not None]
            stats.append('{%.4g, %.4g, %.4g}' % (percentile(values, 25), statistics.median(values), percentile(values, 75)))
        out.append('    Reference{"%s", "%s", %d, %s},' % (group, stem, len(rows), ', '.join(stats)))
    taped = [r for (_, transfer), r in takes.items() if transfer == 'taped']
    out.append('    Reference{"Iowa_tuba_taped", "bass", %d, %s},' % (len(taped), ', '.join(
        '{%.4g, %.4g, %.4g}' % (min(r[name] for r in taped), statistics.mean(r[name] for r in taped), max(r[name] for r in taped)) for name in FEATURES)))
    out += ['};', '', '}  // namespace honkr::corpus', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
